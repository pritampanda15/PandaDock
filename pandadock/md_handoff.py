def _gromacs_script(ligand_charge: int, duration_ns: float) -> str:
    return f"""#!/usr/bin/env bash
# Auto-generated by PandaDock v{__version__} (`pandadock to-md`).
# GROMACS + ACPYPE protein-ligand explicit-solvent MD workflow ({duration_ns:.1f} ns).
set -euo pipefail

echo "[1/7] Parameterizing ligand with ACPYPE (GAFF2, net charge {ligand_charge})..."
acpype -i ligand.sdf -c bcc -n {ligand_charge} -a gaff2 -o gmx

echo "[2/7] Preparing receptor topology (AMBER99SB-ILDN / TIP3P)..."
gmx pdb2gmx -f receptor.pdb -o receptor_processed.gro -water tip3p -ff amber99sb-ildn -ignh

echo "[3/7] Combining complex coordinates and topology..."
echo "Include ligand_GMX.itp into topol.top and append LIG 1 under [ molecules ] before production."

echo "[4/7] Defining dodecahedron box and solvating..."
gmx editconf -f complex.pdb -o boxed.gro -bt dodecahedron -d 1.0
gmx solvate -cp boxed.gro -cs spc216.gro -p topol.top -o solvated.gro

echo "[5/7] Adding neutralizing 0.15 M NaCl ions..."
gmx grompp -f mdp/em.mdp -c solvated.gro -p topol.top -o ions.tpr -maxwarn 1
echo "SOL" | gmx genion -s ions.tpr -o solv_ions.gro -p topol.top -pname NA -nname CL -neutral -conc 0.15

echo "[6/7] Energy minimization + NVT + NPT equilibration..."
gmx grompp -f mdp/em.mdp -c solv_ions.gro -p topol.top -o em.tpr
gmx mdrun -v -deffnm em
gmx grompp -f mdp/nvt.mdp -c em.gro -r em.gro -p topol.top -o nvt.tpr
gmx mdrun -deffnm nvt
gmx grompp -f mdp/npt.mdp -c nvt.gro -r nvt.gro -t nvt.cpt -p topol.top -o npt.tpr
gmx mdrun -deffnm npt

echo "[7/7] Production MD ({duration_ns:.1f} ns)..."
gmx grompp -f mdp/md.mdp -c npt.gro -t npt.cpt -p topol.top -o md.tpr
gmx mdrun -deffnm md
echo "Done. Launch ./analyze_with_pandainsight.sh for trajectory analysis & publication report."
"""


def _pandainsight_script(ligand_name: str) -> str:
    return f"""#!/usr/bin/env bash
# Auto-generated by PandaDock v{__version__} -> PandaInsight MD analysis handoff.
set -euo pipefail

if [ -f "trajectory.dcd" ] && [ -f "solvated_minimized.pdb" ]; then
    pandainsight analyze --topology solvated_minimized.pdb --trajectory trajectory.dcd \\
        --ligand-name "{ligand_name}" --output pandainsight_report/
elif [ -f "md.xtc" ] && [ -f "md.tpr" ]; then
    pandainsight analyze --topology md.tpr --trajectory md.xtc \\
        --ligand-name "{ligand_name}" --output pandainsight_report/
else
    echo "No trajectory found yet. Run python run_openmm.py or bash run_gromacs.sh first."
    exit 1
fi
"""


def export_md_package(
    output_dir: str,
    receptor_file: str,
    ligand_sdf: Optional[str] = None,
    complex_pdb: Optional[str] = None,
    pose_index: int = 0,
    engine: str = "both",
    duration_ns: float = 10.0,
    temperature_k: float = 300.0,
    ionic_strength_m: float = 0.15,
    padding_nm: float = 1.0,
) -> Dict[str, Any]:
    """Build a self-contained MD handoff directory from docked receptor + ligand pose."""
    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)

    rec_src = Path(receptor_file)
    if not rec_src.exists():
        raise FileNotFoundError(f"Receptor PDB not found: {receptor_file}")

    rec_dst = out / "receptor.pdb"
    shutil.copy2(rec_src, rec_dst)

    # Extract selected pose into ligand.sdf (with explicit hydrogens for force-field typing)
    lig_mol = None
    if ligand_sdf and Path(ligand_sdf).exists():
        mols = [m for m in Chem.SDMolSupplier(str(ligand_sdf), removeHs=False) if m is not None]
        if not mols:
            raise ValueError(f"No valid poses found in {ligand_sdf}")
        idx = min(max(0, int(pose_index)), len(mols) - 1)
        lig_mol = Chem.AddHs(mols[idx], addCoords=True)
        w = Chem.SDWriter(str(out / "ligand.sdf"))
        w.write(lig_mol)
        w.close()

    # Write combined complex.pdb
    complex_dst = out / "complex.pdb"
    if complex_pdb and Path(complex_pdb).exists():
        shutil.copy2(complex_pdb, complex_dst)
    else:
        rec_lines = [
            ln for ln in rec_dst.read_text(encoding="utf-8", errors="ignore").splitlines()
            if not ln.startswith("END")
        ]
        lig_lines = []
        if lig_mol is not None:
            pdb_block = Chem.MolToPDBBlock(lig_mol)
            for ln in pdb_block.splitlines():
                if ln.startswith(("ATOM", "HETATM", "CONECT")):
                    if ln.startswith("ATOM  "):
                        ln = "HETATM" + ln[6:]
                    if ln.startswith("HETATM") and len(ln) >= 26:
                        ln = ln[:17] + "LIG" + " L" + "   1" + ln[26:]
                    lig_lines.append(ln)
        complex_dst.write_text("\n".join(rec_lines + ["TER"] + lig_lines + ["END"]) + "\n", encoding="utf-8")

    lig_name = lig_mol.GetProp("_Name") if (lig_mol is not None and lig_mol.HasProp("_Name")) else "LIG"
    net_charge = int(Chem.GetFormalCharge(lig_mol)) if lig_mol is not None else 0
    formula = rdMolDescriptors.CalcMolFormula(lig_mol) if lig_mol is not None else ""
    mw = round(float(Descriptors.MolWt(lig_mol)), 2) if lig_mol is not None else 0.0

    files_written = ["receptor.pdb", "complex.pdb"]
    if lig_mol is not None:
        files_written.append("ligand.sdf")

    eng = (engine or "both").lower()
    if eng in ("openmm", "both"):
        omm_path = out / "run_openmm.py"
        omm_path.write_text(
            _openmm_script(duration_ns, temperature_k, ionic_strength_m, padding_nm),
            encoding="utf-8",
        )
        omm_path.chmod(omm_path.stat().st_mode | stat.S_IXUSR)
        files_written.append("run_openmm.py")

    if eng in ("gromacs", "both"):
        mdp_dir = out / "mdp"
        mdp_dir.mkdir(exist_ok=True)
        for fname, content in _gromacs_mdps(duration_ns, temperature_k).items():
            (mdp_dir / fname).write_text(content, encoding="utf-8")
            files_written.append(f"mdp/{fname}")
        gmx_path = out / "run_gromacs.sh"
        gmx_path.write_text(_gromacs_script(net_charge, duration_ns), encoding="utf-8")
        gmx_path.chmod(gmx_path.stat().st_mode | stat.S_IXUSR)
        files_written.append("run_gromacs.sh")

    pi_path = out / "analyze_with_pandainsight.sh"
    pi_path.write_text(_pandainsight_script(lig_name), encoding="utf-8")
    pi_path.chmod(pi_path.stat().st_mode | stat.S_IXUSR)
    files_written.append("analyze_with_pandainsight.sh")

    manifest = {
        "pandadock_version": __version__,
        "generated_at": datetime.now().isoformat(timespec="seconds"),
        "engine": eng,
        "receptor_source": str(rec_src),
        "ligand_name": lig_name,
        "ligand_formula": formula,
        "ligand_mw": mw,
        "ligand_formal_charge": net_charge,
        "pose_index": int(pose_index),
        "duration_ns": float(duration_ns),
        "temperature_k": float(temperature_k),
        "ionic_strength_m": float(ionic_strength_m),
        "files": files_written,
    }
    (out / "md_handoff_manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    return manifest
