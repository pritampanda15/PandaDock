"""
One-command Dock-to-MD Handoff (`pandadock to-md` / `pandadock dock --export-md`).

Exports a clean, self-contained molecular dynamics starter package from any
PandaDock docking output directory or `(receptor.pdb, pose.sdf)` pair:
- `complex.pdb`, `receptor.pdb`, `ligand.sdf`, `ligand.mol2` (optional)
- `run_openmm.py` (Amber14 + OpenFF / GAFF explicit-solvent TIP3P equilibration + production MD)
- `run_gromacs.sh` + `mdp/{em,nvt,npt,md}.mdp` (GROMACS 2023+ workflow)
- `analyze_with_pandainsight.sh` (direct handoff to PandaInsight MD analysis & PDF reporting)
- `md_handoff_manifest.json` (provenance, ligand charge/formula, box dimensions, PoseBusters status)
"""

from __future__ import annotations

import json
import logging
import os
import shutil
import stat
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, Optional

from rdkit import Chem
from rdkit.Chem import Descriptors, rdMolDescriptors

from . import __version__

logger = logging.getLogger("pandadock.md_handoff")


def _openmm_script(
    duration_ns: float,
    temperature_k: float,
    ionic_strength_m: float,
    padding_nm: float,
) -> str:
    n_steps = max(5000, int(round(duration_ns * 500_000)))  # 2 fs timestep -> 500,000 steps/ns
    return f'''#!/usr/bin/env python3
"""
Auto-generated by PandaDock v{__version__} (`pandadock to-md`).
Explicit-solvent OpenMM MD simulation of the docked protein-ligand complex.

Dependencies (conda / mamba):
    mamba install -c conda-forge openmm openmmforcefields openff-toolkit pdbfixer mdtraj
"""

from pathlib import Path
import openmm as mm
from openmm import app, unit
from openff.toolkit import Molecule
from openmmforcefields.generators import SMIRNOFFTemplateGenerator


def main():
    workdir = Path(__file__).resolve().parent
    receptor_pdb = workdir / "receptor.pdb"
    ligand_sdf = workdir / "ligand.sdf"

    print(f"[PandaDock->OpenMM] Loading {{receptor_pdb.name}} and {{ligand_sdf.name}}")
    off_mol = Molecule.from_file(str(ligand_sdf), allow_undefined_stereo=True)
    smirnoff = SMIRNOFFTemplateGenerator(molecules=off_mol, forcefield="openff-2.2.0.offxml")

    forcefield = app.ForceField("amber14-all.xml", "amber14/tip3pfb.xml")
    forcefield.registerTemplateGenerator(smirnoff.generator)

    pdb = app.PDBFile(str(receptor_pdb))
    modeller = app.Modeller(pdb.topology, pdb.positions)
    modeller.addHydrogens(forcefield, pH=7.4)

    lig_top = off_mol.to_topology().to_openmm()
    lig_pos = off_mol.conformers[0].to_openmm()
    modeller.add(lig_top, lig_pos)

    print("[PandaDock->OpenMM] Solvating in TIP3P water box ({padding_nm:.2f} nm padding, {ionic_strength_m:.2f} M NaCl)...")
    modeller.addSolvent(
        forcefield,
        model="tip3p",
        padding={padding_nm:.2f} * unit.nanometer,
        ionicStrength={ionic_strength_m:.2f} * unit.molar,
    )

    system = forcefield.createSystem(
        modeller.topology,
        nonbondedMethod=app.PME,
        nonbondedCutoff=1.0 * unit.nanometer,
        constraints=app.HBonds,
        hydrogenMass=1.5 * unit.amu,
    )
    system.addForce(mm.MonteCarloBarostat(1.0 * unit.bar, {temperature_k:.1f} * unit.kelvin))

    integrator = mm.LangevinMiddleIntegrator(
        {temperature_k:.1f} * unit.kelvin,
        1.0 / unit.picosecond,
        0.002 * unit.picosecond,
    )
    simulation = app.Simulation(modeller.topology, system, integrator)
    simulation.context.setPositions(modeller.positions)

    print("[PandaDock->OpenMM] Energy minimization...")
    simulation.minimizeEnergy(maxIterations=2000)

    with open(workdir / "solvated_minimized.pdb", "w") as fh:
        state = simulation.context.getState(getPositions=True)
        app.PDBFile.writeFile(modeller.topology, state.getPositions(), fh)

    print("[PandaDock->OpenMM] Equilibrating 100 ps NPT...")
    simulation.context.setVelocitiesToTemperature({temperature_k:.1f} * unit.kelvin)
    simulation.step(50_000)

    print(f"[PandaDock->OpenMM] Running {duration_ns:.1f} ns production MD ({n_steps:,} steps)...")
    simulation.reporters.append(app.DCDReporter(str(workdir / "trajectory.dcd"), 5000))
    simulation.reporters.append(
        app.StateDataReporter(
            str(workdir / "md_log.csv"),
            5000,
            step=True,
            time=True,
            potentialEnergy=True,
            temperature=True,
            density=True,
            speed=True,
        )
    )
    simulation.step({n_steps})
    print("[PandaDock->OpenMM] Complete. Run ./analyze_with_pandainsight.sh for trajectory analysis.")


if __name__ == "__main__":
    main()
'''


